# it creates an array of evenly spaced values within a given interval

# example code : 
#  creates a numpy array containing values from 5 to 9 using np.arange() function
import numpy as np
a = np.arange(5, 10)
print("Array of evenly spaced values: ", a)

# syntax : 
# numpy.arange(start, stop, step, dtype=None)

# Parameters:
# start (optional): The starting value of the sequence. Default is 0.
# stop: The endpoint of the sequence, exclusive.
# step (optional): The spacing between consecutive values. Default is 1.
# dtype (optional): The desired data type of the output array.

